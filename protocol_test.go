func TestDrawBarLevels(t *testing.T) {
	cases := []struct {
		name  string
		value int
		live  map[int]uint8
	}{
		{"zero is blank", 0, nil},
		{"one lights first level", 1, map[int]uint8{6: 0x40}},
		{"ten lights first level", 10, map[int]uint8{6: 0x40}},
		{"eleven lights two levels", 11, map[int]uint8{6: 0x40, 8: 0x40}},
		{"ninety lights nine levels", 90, map[int]uint8{
			1: 0x01, 2: 0x40, 3: 0x01, 4: 0x40, 5: 0x01,
			6: 0x40, 8: 0x40, 10: 0x40, 12: 0x40,
		}},
		{"ninety one lights all levels", 91, map[int]uint8{
			0: 0x40, 1: 0x01, 2: 0x40, 3: 0x01, 4: 0x40, 5: 0x01,
			6: 0x40, 8: 0x40, 10: 0x40, 12: 0x40,
		}},
		{"max int lights all levels", math.MaxInt, map[int]uint8{
			0: 0x40, 1: 0x01, 2: 0x40, 3: 0x01, 4: 0x40, 5: 0x01,
			6: 0x40, 8: 0x40, 10: 0x40, 12: 0x40,
		}},
	}
	for _, tt := range cases {
		t.Run(tt.name, func(t *testing.T) {
			var live, want [64]byte
			for i, mask := range tt.live {
				want[i] = mask
			}
			drawBar(live[:], tt.value, cpuBarSeg)
			if live != want {
				t.Fatalf("drawBar(%d) = %v, want %v", tt.value, live, want)
			}
		})
	}
}

func mustHex(t *testing.T, frame []byte) [64]byte {
	t.Helper()
	fields := frame
	if len(fields) != 64 {
		t.Fatalf("golden frame must be 64 bytes, got %d", len(fields))
	}
	var out [64]byte
	copy(out[:], fields)
	return out
}

